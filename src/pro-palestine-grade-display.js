/* Project-owned Jev model scores; separate from source-publisher grades. */
const ProPalestineGradeDisplay = {
  render(candidate, data, {node}) {
    const grade=candidate.pro_palestine_score_grade,score=candidate.pro_palestine_score,meta=candidate.pro_palestine_evaluation;
    const valid=meta&&typeof score==='number'&&Number.isFinite(score)&&score>=0&&score<=5&&/^[A-F]$/.test(grade);
    const badge=node('a','pro-palestine-grade grade-'+(valid?grade.toLowerCase():'na'),valid?grade+' ('+score.toFixed(2)+' / 5)':'N/A');
    badge.href=data.pro_palestine_grading?.methodology_url||'https://github.com/salqadri/bay-area-elections-2026/blob/main/docs/PUBLISHED_GRADES.md';
    badge.target='_blank';badge.rel='noopener noreferrer';
    let description='Jev pro-Palestine model grade: '+(valid?grade+', score '+score.toFixed(2)+' out of 5':meta?(meta.evidence_score<(data.pro_palestine_grading?.evidence_threshold??.10)?'N/A: insufficient evidence (below '+(data.pro_palestine_grading?.evidence_threshold??.10)+' / 1)':'N/A: insufficient issue-specific evidence'):'N/A: no saved evaluation');
    if(meta){if(valid)description+=' · Model score confidence: '+(meta.confidence*100).toFixed(1)+'%';description+=' · Evidence: '+meta.evidence_score+' / 1 · Evaluated '+new Date(meta.evaluated_at).toLocaleString('en-US',{timeZone:'America/Los_Angeles',dateStyle:'medium',timeStyle:'short'})+' PT';}
    description+=' · View rubric and methodology';badge.title=description;badge.setAttribute('aria-label',description);
    return badge;
  },
  renderExplanation(candidate,{node}) {
    if(!/^[A-F]$/.test(candidate.pro_palestine_score_grade||''))return null;
    const explanation=candidate.pro_palestine_explanation;
    if(!explanation||typeof explanation.summary!=='string'||!explanation.summary.trim())return null;
    const details=node('details','grade-explanation');
    details.append(node('summary',null,'Why this grade?'));
    const inputVersion=Number((candidate.pro_palestine_evaluation?.input_state_version||'').match(/-v(\d+)/)?.[1]);
    if(inputVersion&&inputVersion<11&&(candidate.gaza_evidence||[]).some(item=>item.dimension==='aipac_funding')){
      details.append(node('p','grade-explanation-note','Funding evidence rules changed after this saved evaluation. Its grade and explanation may include historical or mixed-donor totals excluded from new evaluations; they have not been rerun.'));
    }
    details.append(node('p','grade-explanation-text',explanation.summary.trim()));
    details.append(node('p','grade-explanation-note','Model-written evidence summary of the recorded evidence for this saved score (generated by '+explanation.model+'). It explains the published grade and never changes it.'));
    return details;
  }
};
